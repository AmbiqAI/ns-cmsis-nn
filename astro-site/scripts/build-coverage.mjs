/*
 * API extraction owns C declaration parsing; coverage narrows that model to
 * public kernel headers. Family classification matches the reference index,
 * while build groups come from the CMake manifest. Refs #524.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(siteRoot, '..');
const outFile = path.join(siteRoot, 'src', 'data', 'coverage.json');

// API formats include unsigned kernels in addition to the build's dtype selectors.
const DTYPES = ['s4', 's8', 's16', 's32', 's64', 'u8', 'q7', 'q15', 'f16', 'f32'];

const config = JSON.parse(
  fs.readFileSync(path.join(siteRoot, 'reference.config.json'), 'utf8'),
);

const headerDir = path.join(repoRoot, 'Include');
const headers = fs
  .readdirSync(headerDir)
  .filter((name) => /^arm_nnfunctions.*\.h$/.test(name))
  .sort();

// The reference model handles multiline prototypes and conditional float APIs.
// Restrict the inventory to the public kernel headers, excluding internal helpers.
const model = JSON.parse(fs.readFileSync(
  path.join(siteRoot, 'public/reference/api/reference.json'), 'utf8',
));
const functions = new Set();
const perHeaderNames = Object.fromEntries(headers.map((name) => [name, new Set()]));
function visit(module) {
  for (const symbol of module.symbols ?? []) {
    const header = symbol.source?.path?.replace(/^Include\//, '');
    if (symbol.kind !== 'function' || !perHeaderNames[header]) continue;
    perHeaderNames[header].add(symbol.name);
    functions.add(symbol.name);
  }
  for (const child of module.submodules ?? []) visit(child);
}
for (const module of model.modules ?? []) visit(module);
const perHeader = Object.fromEntries(
  Object.entries(perHeaderNames).map(([name, names]) => [name, names.size]),
);
if (headers.some((name) => perHeader[name] === 0)) {
  throw new Error('Public kernel header missing from API model; regenerate the reference.');
}

function tagsOf(name) {
  return name
    .split('_')
    .map((segment) => segment === 'fp16' ? 'f16' : segment)
    .filter((segment) => DTYPES.includes(segment))
    .filter((segment, index, all) => all.indexOf(segment) === index);
}

const compiled = config.groups.map((group) => ({
  id: group.id,
  label: group.label,
  blurb: group.blurb,
  regexes: group.patterns.map((pattern) => new RegExp(pattern)),
}));

const sorted = [...functions].sort();
const families = compiled.map((group) => {
  const members = sorted.filter((fn) => compiled.find((candidate) =>
    candidate.regexes.some((re) => re.test(fn)))?.id === group.id);
  const counts = Object.fromEntries(DTYPES.map((dtype) => [dtype, 0]));
  let untyped = 0;
  for (const fn of members) {
    const tags = tagsOf(fn);
    if (tags.length === 0) untyped += 1;
    for (const tag of tags) counts[tag] += 1;
  }
  return {
    id: group.id,
    label: group.label,
    blurb: group.blurb,
    functions: members.length,
    href: `${config.base}reference/api/${group.id}/`,
    untyped,
    counts,
  };
});

const claimed = new Set(
  families.flatMap((family) =>
    sorted.filter((fn) =>
      compiled
        .find((group) => group.id === family.id)
        .regexes.some((re) => re.test(fn)),
    ),
  ),
);

const byDtype = Object.fromEntries(
  DTYPES.map((dtype) => [
    dtype,
    sorted.filter((fn) => tagsOf(fn).includes(dtype)).length,
  ]),
);

const cmakeText = fs.readFileSync(
  path.join(repoRoot, 'cmake', 'ns_cmsis_nn.cmake'),
  'utf8',
);
const groupBlock = cmakeText.match(
  /set\(_NS_CMSIS_NN_GROUPS\s*([\s\S]*?)\)/,
);
const operatorGroups = groupBlock
  ? groupBlock[1].split(/\s+/).filter((id) => id !== '')
  : [];

const coverage = {
  note:
    'Generated by astro-site/scripts/build-coverage.mjs from the public ' +
    'API model (public kernel headers) and cmake/ns_cmsis_nn.cmake. Do not edit by hand.',
  headers,
  functionsByHeader: perHeader,
  dtypes: DTYPES,
  totals: {
    functions: sorted.length,
    inAFamily: claimed.size,
    byDtype,
  },
  families,
  operatorGroups: {
    count: operatorGroups.length,
    ids: operatorGroups,
    source: 'cmake/ns_cmsis_nn.cmake',
  },
  apiGroups: config.groups.length,
};

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${JSON.stringify(coverage, null, 2)}\n`);

console.log(
  `build-coverage: ${sorted.length} declared functions across ` +
    `${headers.length} headers -> src/data/coverage.json`,
);
for (const family of families) {
  console.log(`  ${family.id}: ${family.functions}`);
}
console.log(`  in no family: ${sorted.length - claimed.size}`);
console.log(`  operator groups in the CMake source of truth: ${operatorGroups.length}`);
