/*
 * Derive the data-type-by-family matrix from the public kernel headers
 * (AmbiqAI/ns-cmsis-nn#524) and write it to src/data/coverage.json.
 *
 * The declarations in Include/arm_nnfunctions*.h are the only statement of
 * what the library exposes that cannot drift from the code, and a kernel's
 * data types are written into its name as `_s8`, `_s16`, `_f16` and the rest.
 * The families are the ones reference.config.json already defines for the API
 * index, so the site names an operator family the same way in both places.
 *
 * The operator group ids come from cmake/ns_cmsis_nn.cmake, the build's single
 * source of truth for the source layout, so the count on the landing page is
 * the count the build uses.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(siteRoot, '..');
const outFile = path.join(siteRoot, 'src', 'data', 'coverage.json');

/* The tag list is `_NS_CMSIS_NN_DTYPES` in cmake/ns_cmsis_nn.cmake, in the
   order that file writes it, so the table columns follow the build's
   vocabulary rather than an editorial one. */
const DTYPES = ['s4', 's8', 's16', 's32', 's64', 'q7', 'q15', 'f16', 'f32'];

const config = JSON.parse(
  fs.readFileSync(path.join(siteRoot, 'reference.config.json'), 'utf8'),
);

const headerDir = path.join(repoRoot, 'Include');
const headers = fs
  .readdirSync(headerDir)
  .filter((name) => /^arm_nnfunctions.*\.h$/.test(name))
  .sort();

/* A declaration is a line that names a return type and then a function. Lines
   inside the Doxygen comment blocks start with `*`, and the usage examples
   they carry would otherwise be counted as declarations. */
function declaredFunctions(text) {
  const names = new Set();
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line === '' || line.startsWith('*') || line.startsWith('/') || line.startsWith('#')) {
      continue;
    }
    const match = line.match(/^[A-Za-z_][\w\s*]*?\b(arm_[a-z0-9_]+)\s*\(/);
    if (match) names.add(match[1]);
  }
  return names;
}

const functions = new Set();
const perHeader = {};
for (const name of headers) {
  const found = declaredFunctions(
    fs.readFileSync(path.join(headerDir, name), 'utf8'),
  );
  perHeader[name] = found.size;
  for (const fn of found) functions.add(fn);
}

function tagsOf(name) {
  return name
    .split('_')
    .filter((segment) => DTYPES.includes(segment))
    .filter((segment, index, all) => all.indexOf(segment) === index);
}

const compiled = config.groups.map((group) => ({
  id: group.id,
  label: group.label,
  blurb: group.blurb,
  regexes: group.patterns.map((pattern) => new RegExp(pattern)),
}));

const sorted = [...functions].sort();
const families = compiled.map((group) => {
  const members = sorted.filter((fn) => group.regexes.some((re) => re.test(fn)));
  const counts = Object.fromEntries(DTYPES.map((dtype) => [dtype, 0]));
  let untyped = 0;
  for (const fn of members) {
    const tags = tagsOf(fn);
    if (tags.length === 0) untyped += 1;
    for (const tag of tags) counts[tag] += 1;
  }
  return {
    id: group.id,
    label: group.label,
    blurb: group.blurb,
    functions: members.length,
    untyped,
    counts,
  };
});

const claimed = new Set(
  families.flatMap((family) =>
    sorted.filter((fn) =>
      compiled
        .find((group) => group.id === family.id)
        .regexes.some((re) => re.test(fn)),
    ),
  ),
);

const byDtype = Object.fromEntries(
  DTYPES.map((dtype) => [
    dtype,
    sorted.filter((fn) => tagsOf(fn).includes(dtype)).length,
  ]),
);

const cmakeText = fs.readFileSync(
  path.join(repoRoot, 'cmake', 'ns_cmsis_nn.cmake'),
  'utf8',
);
const groupBlock = cmakeText.match(
  /set\(_NS_CMSIS_NN_GROUPS\s*([\s\S]*?)\)/,
);
const operatorGroups = groupBlock
  ? groupBlock[1].split(/\s+/).filter((id) => id !== '')
  : [];

const coverage = {
  note:
    'Generated by astro-site/scripts/build-coverage.mjs from the public ' +
    'headers and cmake/ns_cmsis_nn.cmake. Do not edit by hand.',
  headers,
  functionsByHeader: perHeader,
  dtypes: DTYPES,
  totals: {
    functions: sorted.length,
    inAFamily: claimed.size,
    byDtype,
  },
  families,
  operatorGroups: {
    count: operatorGroups.length,
    ids: operatorGroups,
    source: 'cmake/ns_cmsis_nn.cmake',
  },
  apiGroups: config.groups.length,
};

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${JSON.stringify(coverage, null, 2)}\n`);

console.log(
  `build-coverage: ${sorted.length} declared functions across ` +
    `${headers.length} headers -> src/data/coverage.json`,
);
for (const family of families) {
  console.log(`  ${family.id}: ${family.functions}`);
}
console.log(`  in no family: ${sorted.length - claimed.size}`);
console.log(`  operator groups in the CMake source of truth: ${operatorGroups.length}`);
