"""Generate the test data of test_arm_layer_norm_s8 / _s16 / _f32 from layer_norm_reference.py.

    python3 Tests/UnitTest/generate_layer_norm_data.py

Integer expectations are the reference's exact outputs (the same in either requantization rounding mode). Row sizes cover full vectors and every MVE tail length (16-lane statistics,
4-lane output), and the rows of each case mix spread-out, constant, extreme and nearly constant values. Float
expectations are float64 layer norm rounded to float32; the test compares with a tolerance.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import layer_norm_reference as R  # noqa: E402
CASES_DIR = HERE / "TestCases"

LICENSE = """/*
 * SPDX-FileCopyrightText: Copyright 2026 Ambiq. All rights reserved.
 *
 * SPDX-License-Identifier: Apache-2.0
 */
/* Generated by Tests/UnitTest/generate_layer_norm_data.py from layer_norm_reference.py -- do not edit. */
"""

# (rows, row_size, epsilon, gamma kind)
INT_CASES = [
    (2, 1, 1e-5, "random"),
    (3, 5, 1e-5, "random"),
    (4, 16, 1e-5, "random"),
    (4, 17, 0.0, "random"),
    (3, 31, 1e-5, "identity"),
    (2, 64, 1e-3, "random"),
    (3, 100, 1e-5, "random"),
    (2, 257, 1.0, "random"),
    (1, 768, 1e-5, "random"),
]


def _rows(dtype: str, rows: int, n: int, rng: np.random.Generator) -> np.ndarray:
    info = np.iinfo(np.int8 if dtype == "s8" else np.int16)
    out = []
    for r in range(rows):
        kind = ("spread", "constant", "extreme", "tiny")[r % 4] if rows > 1 else "spread"
        if kind == "spread":
            row = np.round(rng.normal(rng.normal(0, 10), info.max / 5, n))
        elif kind == "constant":
            row = np.full(n, int(rng.integers(info.min, info.max + 1)))
        elif kind == "extreme":
            row = rng.choice([info.min, info.max], n)
        else:
            row = rng.integers(-2, 3, n) + int(rng.integers(-50, 50))
        out.append(np.clip(row, info.min, info.max))
    return np.array(out).astype(info.dtype)


def _c_array(ctype: str, name: str, values) -> str:
    vals = [str(int(v)) for v in np.asarray(values).ravel()]
    body = ",\n".join("    " + ", ".join(vals[i:i + 16]) for i in range(0, len(vals), 16))
    return f"static const {ctype} {name}[{len(vals)}] = {{\n{body}}};\n"


def gen_int(dtype: str) -> str:
    ctype = "int8_t" if dtype == "s8" else "int16_t"
    info = np.iinfo(np.int8 if dtype == "s8" else np.int16)
    rng = np.random.default_rng(20261105 if dtype == "s8" else 20261106)
    parts, table = [LICENSE, "#pragma once\n#include <stdint.h>\n\n"], []
    for i, (rows, n, eps, gamma_kind) in enumerate(INT_CASES):
        x = _rows(dtype, rows, n, rng)
        if gamma_kind == "identity":
            gamma, beta = None, None
        else:
            gamma = rng.normal(1.0, 0.5, n)
            gamma[rng.random(n) < 0.25] *= -1
            gamma[::11] = 0.0
            beta = rng.normal(0.0, 0.5, n)
        in_scale = float(rng.uniform(0.005, 0.05)) / (1 if dtype == "s8" else 128)
        out_scale = float(rng.uniform(3.0, 6.0)) / info.max
        out_zp = int(rng.integers(-20, 20)) if dtype == "s8" else 0
        p = R.export_params(gamma, beta, eps, in_scale, out_scale, out_zp, n, dtype)
        y = R.layer_norm_int(x, p)
        tag = f"ln_{dtype}_{i}"
        parts += [
            _c_array(ctype, f"{tag}_input", x),
            _c_array("int32_t", f"{tag}_gamma", p.gamma),
            _c_array("int32_t", f"{tag}_bias", p.bias),
            _c_array(ctype, f"{tag}_expected", y),
            "\n",
        ]
        table.append(f"    {{{rows}, {n}, {p.epsilon}LL, {p.output_shift}, {p.act_min}, {p.act_max}, {tag}_input, "
                     f"{tag}_gamma, {tag}_bias, {tag}_expected}},\n")
    parts += [
        "typedef struct\n{\n    int32_t rows;\n    int32_t row_size;\n    int64_t epsilon;\n    int32_t output_shift;\n"
        f"    int32_t act_min;\n    int32_t act_max;\n    const {ctype} *input;\n    const int32_t *gamma;\n"
        f"    const int32_t *bias;\n    const {ctype} *expected;\n}} layer_norm_{dtype}_case;\n\n",
        f"static const layer_norm_{dtype}_case layer_norm_{dtype}_cases[] = {{\n", *table, "};\n",
        f"#define LAYER_NORM_{dtype.upper()}_NUM_CASES {len(table)}\n",
    ]
    return "".join(parts)


def gen_f32() -> str:
    rng = np.random.default_rng(20261107)
    parts, table = [LICENSE, "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"], []

    def farr(name, values):
        vals = [f"{float(v)!r}f".replace("inff", "INFINITY") for v in np.asarray(values, dtype=np.float32).ravel()]
        body = ",\n".join("    " + ", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8))
        return f"static const float {name}[{len(vals)}] = {{\n{body}}};\n"

    for i, (rows, n, eps, affine) in enumerate([(2, 1, 1e-5, True), (3, 7, 1e-5, True), (2, 16, 1e-6, False),
                                                (3, 33, 1e-5, True), (2, 129, 1e-2, True), (1, 768, 1e-5, True)]):
        x = rng.normal(rng.normal(0, 3), rng.uniform(0.1, 4), (rows, n)).astype(np.float32)
        if rows > 1:
            x[1] = np.float32(1.25)  # a constant row normalizes to beta
        gamma = rng.normal(1, 0.5, n).astype(np.float32) if affine else None
        beta = rng.normal(0, 0.5, n).astype(np.float32) if affine else None
        y = R.layer_norm_float(x.astype(np.float64), gamma, beta, eps).astype(np.float32)
        tag = f"ln_f32_{i}"
        parts += [farr(f"{tag}_input", x), farr(f"{tag}_expected", y)]
        if affine:
            parts += [farr(f"{tag}_gamma", gamma), farr(f"{tag}_beta", beta)]
        g, b = (f"{tag}_gamma", f"{tag}_beta") if affine else ("NULL", "NULL")
        table.append(f"    {{{rows}, {n}, {float(np.float32(eps))!r}f, {tag}_input, {g}, {b}, {tag}_expected}},\n")
    parts += [
        "typedef struct\n{\n    int32_t rows;\n    int32_t row_size;\n    float epsilon;\n    const float *input;\n"
        "    const float *gamma;\n    const float *beta;\n    const float *expected;\n} layer_norm_f32_case;\n\n",
        "static const layer_norm_f32_case layer_norm_f32_cases[] = {\n", *table, "};\n",
        f"#define LAYER_NORM_F32_NUM_CASES {len(table)}\n",
    ]
    return "".join(parts)


def main() -> None:
    for dtype in ("s8", "s16"):
        d = CASES_DIR / f"test_arm_layer_norm_{dtype}"
        d.mkdir(exist_ok=True)
        (d / f"layer_norm_{dtype}_data.h").write_text(gen_int(dtype))
    d = CASES_DIR / "test_arm_layer_norm_f32"
    d.mkdir(exist_ok=True)
    (d / "layer_norm_f32_data.h").write_text(gen_f32())


if __name__ == "__main__":
    main()
