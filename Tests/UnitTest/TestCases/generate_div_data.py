from pathlib import Path
import random, struct

# Exact rational IEEE round-to-nearest-even oracle, independent of compiler float division.
def divbits(a,b,bits):
 p,e=(23,8) if bits==32 else (10,5); bias=(1<<(e-1))-1;em=(1<<e)-1;frac=(1<<p)-1
 sign=(a^b)&(1<<(bits-1));ea=(a>>p)&em;eb=(b>>p)&em;fa=a&frac;fb=b&frac
 nan=(em<<p)|(1<<(p-1));inf=em<<p
 if (ea==em and fa) or (eb==em and fb) or ((a&~(1<<(bits-1)))==0 and (b&~(1<<(bits-1)))==0) or (ea==em and eb==em):return nan
 if ea==em or (eb==0 and fb==0):return sign|inf
 if eb==em or (ea==0 and fa==0):return sign
 na=(1<<p)|fa if ea else fa;nb=(1<<p)|fb if eb else fb
 shift=(ea if ea else 1)-(eb if eb else 1)
 if shift>=0:na<<=shift
 else:nb<<=-shift
 exponent=na.bit_length()-nb.bit_length()
 if exponent>=0:
  if na<(nb<<exponent):exponent-=1
 elif (na<<(-exponent))<nb:exponent-=1
 scale=p-max(exponent,1-bias)
 num,den=(na<<scale,nb) if scale>=0 else (na,nb<<(-scale))
 q,r=divmod(num,den)
 if 2*r>den or (2*r==den and q&1):q+=1
 if q>=(1<<(p+1)):q>>=1;exponent+=1
 if exponent+bias>=em:return sign|inf
 if exponent<1-bias:return sign|q
 return sign|((exponent+bias)<<p)|(q&frac)
for bits in (32,16):
 tag=f'f{bits}';name=f'test_arm_elementwise_div_{tag}';d=Path(__file__).parent/name
 p,e=(23,8) if bits==32 else (10,5);bias=(1<<(e-1))-1;inf=((1<<e)-1)<<p;sign=1<<(bits-1);one=bias<<p
 pairs=[(a,b) for a in [0,sign,one,sign|one,inf,sign|inf,inf|1,1,sign|1] for b in [0,sign,one,sign|one,inf,1]]
 pairs +=[(inf-1,one-1),(1,one+(1<<p)),(3,one+(1<<p)),(one,3),(one+1,one+3)]
 rng=random.Random(831+bits)
 pairs +=[(rng.getrandbits(bits),rng.getrandbits(bits)) for _ in range(100)]
 # Known division vs rounded reciprocal witnesses are found independently.
 fmt='f' if bits==32 else 'e';uintfmt='I' if bits==32 else 'H'
 def value(x):return struct.unpack('<'+fmt,struct.pack('<'+uintfmt,x))[0]
 def encode(x):
  try:return struct.unpack('<'+uintfmt,struct.pack('<'+fmt,x))[0]
  except OverflowError:return inf|(sign if x<0 else 0)
 for _ in range(10000):
  a=one+rng.randrange(1<<p);b=one+rng.randrange(1<<p)
  wrong=encode(value(a)*value(encode(1/value(b))))
  if wrong!=divbits(a,b,bits):pairs.append((a,b));break
 data='/* SPDX-License-Identifier: Apache-2.0 */\n/* Exact integer-rational DIV expectations; generated by generate_div_data.py. */\n'
 data+=f'static const uint{bits}_t div_cases[][3] = {{\n'+''.join(f'    {{0x{a:0{bits//4}x}, 0x{b:0{bits//4}x}, 0x{divbits(a,b,bits):0{bits//4}x}}},\n' for a,b in pairs)+'};\n'
 (d/'div_data.h').write_text(data)
