"""Generate binary32 subtraction-then-square goldens with NumPy (seed 840)."""
from pathlib import Path

import numpy as np

rng = np.random.default_rng(840)
special = np.array([0, 0x80000000, 1, 0x007FFFFF, 0x00800000, 0x1A000000,
                    0x3F800000, 0x3F800001, 0x33800000, 0xBF800000,
                    0x5F800000, 0x7F7FFFFF, 0xFF7FFFFF, 0x7F800000,
                    0xFF800000, 0x7FC12345], dtype=np.uint32)
a = np.concatenate([np.repeat(special, len(special)), rng.integers(0, 2**32, 257, dtype=np.uint32)])
b = np.concatenate([np.tile(special, len(special)), rng.integers(0, 2**32, 257, dtype=np.uint32)])
with np.errstate(all="ignore"):
    delta = np.subtract(a.view(np.float32), b.view(np.float32), dtype=np.float32)
    result = np.multiply(delta, delta, dtype=np.float32).view(np.uint32)
def flush(values):
    bits = values.view(np.uint32).copy()
    bits[(bits & 0x7F800000) == 0] &= 0x80000000
    return bits.view(np.float32)

with np.errstate(all="ignore"):
    mve_delta = flush(np.subtract(flush(a.view(np.float32)), flush(b.view(np.float32)), dtype=np.float32))
    mve_result = flush(np.multiply(mve_delta, mve_delta, dtype=np.float32)).view(np.uint32)

lines = ["/* SPDX-FileCopyrightText: 2026 Ambiq", " * SPDX-License-Identifier: Apache-2.0",
         " * Generated by ../generate_squared_difference_f32_data.py; NumPy binary32 at each operation. */",
         "#pragma once", "#include <stdint.h>", "static const uint32_t squared_difference_cases[][4] = {"]
lines += [f"    {{0x{x:08x}u, 0x{y:08x}u, 0x{z:08x}u, 0x{m:08x}u}}," for x, y, z, m in zip(a, b, result, mve_result)]
lines += ["};", ""]
Path(__file__).with_name("test_arm_elementwise_squared_difference_f32").joinpath("squared_difference_f32_data.h").write_text("\n".join(lines))
