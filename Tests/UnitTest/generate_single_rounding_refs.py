"""Generate exact single-rounding convolution references from retained test inputs.

Python integers avoid host-width overflow. No production kernel or requantizer
is used. Default-rounding reference files are never modified.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent / 'TestCases' / 'TestData'


def generate(name):
    directory = ROOT / name
    prefix = name.upper() + '_'
    cfg = {key[len(prefix):]: int(value) for key, value in
           re.findall(r'#define\s+(\w+)\s+(-?\d+)', (directory / 'config_data.h').read_text())}

    def array(stem):
        legacy_names = {'input': 'input.h', 'weights': 'input_weights.h',
                        'biases': 'input_bias.h', 'output_ref': 'output.h',
                        'output_mult': 'output_multiplier.h', 'output_shift': 'output_shift.h'}
        filename = legacy_names[stem] if '#include \"input.h\"' in (directory / 'test_data.h').read_text() else stem + '_data.h'
        text = (directory / filename).read_text()
        return [int(x) for x in re.findall(r'-?\d+', text.split('{', 1)[1].split('}', 1)[0])]

    inputs, weights, biases = array('input'), array('weights'), array('biases')
    if 'int4' in name:
        weights = [((byte >> shift) & 15) - (16 if ((byte >> shift) & 8) else 0)
                   for byte in weights for shift in (0, 4)]
    multipliers, shifts = array('output_mult'), array('output_shift')
    output = []
    default_output = []
    for batch in range(cfg['INPUT_BATCHES']):
        for oy in range(cfg['OUTPUT_H']):
            for ox in range(cfg['OUTPUT_W']):
                for oc in range(cfg['OUT_CH']):
                    acc = biases[oc]
                    for ky in range(cfg['FILTER_Y']):
                        iy = oy * cfg['STRIDE_Y'] - cfg['PAD_Y'] + ky * cfg['DILATION_Y']
                        for kx in range(cfg['FILTER_X']):
                            ix = ox * cfg['STRIDE_X'] - cfg['PAD_X'] + kx * cfg['DILATION_X']
                            if not (0 <= iy < cfg['INPUT_H'] and 0 <= ix < cfg['INPUT_W']):
                                continue
                            for ic in range(cfg['IN_CH']):
                                ip = ((batch * cfg['INPUT_H'] + iy) * cfg['INPUT_W'] + ix) * cfg['IN_CH'] + ic
                                wp = ((oc * cfg['FILTER_Y'] + ky) * cfg['FILTER_X'] + kx) * cfg['IN_CH'] + ic
                                acc += (inputs[ip] + cfg['INPUT_OFFSET']) * weights[wp]
                    assert -(1 << 31) <= acc < (1 << 31)
                    total_shift = 31 - shifts[oc]
                    assert 1 <= total_shift <= 62
                    high = ((acc << max(shifts[oc], 0)) * multipliers[oc] + (1 << 30)) >> 31
                    right = max(-shifts[oc], 0)
                    if right:
                        mask = (1 << right) - 1
                        high = (high >> right) + ((high & mask) > ((mask >> 1) + (high < 0)))
                    default_value = high + cfg['OUTPUT_OFFSET']
                    default_output.append(max(cfg['OUT_ACTIVATION_MIN'], min(cfg['OUT_ACTIVATION_MAX'], default_value)))
                    value = (acc * multipliers[oc] + (1 << (total_shift - 1))) >> total_shift
                    value += cfg['OUTPUT_OFFSET']
                    output.append(max(cfg['OUT_ACTIVATION_MIN'], min(cfg['OUT_ACTIVATION_MAX'], value)))
    assert len(output) == cfg['DST_SIZE']
    old = array('output_ref')[:cfg['DST_SIZE']]
    assert default_output == old, (name, [(i,a,b) for i,(a,b) in enumerate(zip(default_output,old)) if a!=b][:12])
    header = '// SPDX-License-Identifier: Apache-2.0\n// Generated by Tests/UnitTest/generate_single_rounding_refs.py.\n#pragma once\n#include <stdint.h>\n\n'
    header += f'const int8_t {name}_output_ref[{len(output)}] = {{\n'
    header += '\n'.join('    ' + ', '.join(map(str, output[i:i + 16])) + ',' for i in range(0, len(output), 16))
    (directory / 'output_ref_single_rounding_data.h').write_text(header + '\n};\n')
    print(name, 'changed outputs:', [(i, a, b) for i, (a, b) in enumerate(zip(old, output)) if a != b])


if __name__ == '__main__':
    for case in ('conv_5', 'conv_2x2_dilation', 'kernel1x1_int4',
                 'kernel1x1_int4_3', 'kernel1x1_stride_x_int4', 'kernel1x1_stride_x_y_int4'):
        generate(case)
